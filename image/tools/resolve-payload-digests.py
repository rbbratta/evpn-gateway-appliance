#!/usr/bin/env python3
"""Resolve payload image digests with skopeo and refresh per-stream .env files.

Usage: image/tools/resolve-payload-digests.py [--write]
  --write  update image/payload-images.yaml and rhel*/payload-images.env

Requires: skopeo, registry.redhat.io auth for openshift4/5 images.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import subprocess
import sys

try:
    import yaml
except ImportError:
    print("resolve-payload-digests: need PyYAML", file=sys.stderr)
    sys.exit(2)

ENV_NAMES = {
    "node_exporter": "NODE_EXPORTER_IMAGE",
    "frr": "FRR_IMAGE",
}


def skopeo_digest(repository: str, tag: str) -> str:
    ref = f"docker://{repository}:{tag}"
    p = subprocess.run(
        [
            "skopeo",
            "inspect",
            "--override-os",
            "linux",
            "--override-arch",
            "amd64",
            ref,
        ],
        capture_output=True,
        text=True,
    )
    if p.returncode != 0:
        raise RuntimeError(p.stderr.strip() or p.stdout.strip())
    data = json.loads(p.stdout)
    digest = data.get("Digest", "")
    if not digest.startswith("sha256:"):
        raise RuntimeError(f"no digest for {ref}")
    return digest


def pullspec(repository: str, digest: str) -> str:
    return f"{repository}@{digest}"


def write_env(path: pathlib.Path, lines: dict[str, str]) -> None:
    body = ["# Generated by image/tools/resolve-payload-digests.py — do not edit.\n"]
    for env_name, value in lines.items():
        body.append(f"{env_name}={value}\n")
    path.write_text("".join(body))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    root = pathlib.Path(__file__).resolve().parents[2]
    inv_path = root / "image" / "payload-images.yaml"
    inv = yaml.safe_load(inv_path.read_text()) or {}

    updates: dict[str, dict[str, dict[str, str]]] = {}
    for stream, block in sorted(inv.items()):
        if not isinstance(block, dict):
            continue
        env_lines: dict[str, str] = {}
        digests: dict[str, str] = {}
        for name, spec in block.items():
            if not isinstance(spec, dict):
                continue
            repo = (spec.get("repository") or "").strip()
            tag = (spec.get("tag") or "").strip()
            if not repo or not tag:
                continue
            digest = skopeo_digest(repo, tag)
            digests[name] = digest
            print(f"{stream} {name} {digest}")
            env_name = ENV_NAMES.get(name)
            if env_name is None:
                print(f"skip unknown image key {stream}.{name}", file=sys.stderr)
                continue
            env_lines[env_name] = pullspec(repo, digest)
        if digests:
            updates[stream] = {"env": env_lines, "digests": digests}

    if not args.write:
        print("dry-run only; pass --write to update files")
        return 0

    for stream, u in updates.items():
        for name, digest in u["digests"].items():
            inv[stream][name]["digest"] = digest
        env_path = root / "image" / stream / "payload-images.env"
        write_env(env_path, u["env"])
    inv_path.write_text(yaml.safe_dump(inv, sort_keys=False))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except RuntimeError as e:
        print(f"resolve-payload-digests: {e}", file=sys.stderr)
        sys.exit(1)
